import jsPDF from 'jspdf';
import { ScanResult } from '../types';

// 1. Function to Download PDF (User clicks button)
export const generateClinicalPDF = (scanResult: ScanResult, imageSrc: string) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  
  // Header
  doc.setFillColor(15, 23, 42); 
  doc.rect(0, 0, pageWidth, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text("PULMOSIGHT AI", 20, 20);
  
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text("CLINICAL DIAGNOSTIC REPORT", 20, 28);
  doc.text(`CASE ID: ${scanResult.patientId}`, pageWidth - 60, 28);

  // Image
  if (imageSrc) {
    doc.addImage(imageSrc, 'PNG', 20, 50, 60, 60);
  }

  // Diagnosis
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text("DIAGNOSTIC RESULT:", 90, 55);
  
  doc.setFontSize(24);
  if (scanResult.diagnosis === 'Normal') doc.setTextColor(0, 150, 0); 
  else doc.setTextColor(200, 0, 0); 
  
  doc.text(scanResult.diagnosis.toUpperCase(), 90, 68);
  
  doc.setFontSize(12);
  doc.setTextColor(80, 80, 80);
  doc.text(`Confidence: ${scanResult.confidence}%`, 90, 78);

  // Report Text
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text("RADIOLOGICAL FINDINGS", 20, 130);
  
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  // Clean up text to prevent overlap
  const cleanReport = scanResult.reportText.replace(/\*/g, '');
  const splitText = doc.splitTextToSize(cleanReport, pageWidth - 40);
  doc.text(splitText, 20, 140);

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text("Generated by PulmoSight AI System.", 20, 280);

  doc.save(`Clinical_Report_${scanResult.patientId}.pdf`);
};

